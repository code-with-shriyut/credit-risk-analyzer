def bulk_insert():
    for app in applications:

        (
            name,
            age,
            income,
            loan_amount,
            tenure_months,
            annual_rate,
            credit_score,
            months_employed
        ) = app

        emi = calculate_emi(loan_amount, annual_rate, tenure_months)
        emi_ratio = emi / income

        risk = risk_classification(
            emi_ratio,
            age,
            tenure_months,
            credit_score,
            months_employed
        )

        decision = evaluate_decision(risk)

        insert_loan_application(
            name,
            age,
            income,
            loan_amount,
            tenure_months,
            annual_rate,
            credit_score,
            months_employed,
            emi,
            emi_ratio,
            risk,
            decision
        )

        print(name, "→", risk, "|", decision)

    print("✅ Controlled bulk insert completed.")


if __name__ == "__main__":
    bulk_insert()